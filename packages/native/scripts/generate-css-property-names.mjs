// Writes js/dom/css-property-names.ts from the `mdn-data` package (MDN's CSS property index), a devDependency used only here.
// Run it after a bump of `mdn-data`: `bun run generate:css-property-names`. The output is committed.
import { createRequire } from "node:module"
import { writeFileSync } from "node:fs"

const require = createRequire(import.meta.url)
const properties = require("mdn-data/css/properties.json")
const version = require("mdn-data/package.json").version

// `--*` is every custom property, which the declaration takes by its prefix; `-ms-` and `-moz-` names are not Chrome's;
// an obsolete property is one no engine takes any more.
const names = Object.keys(properties)
  .filter((name) => !name.startsWith("--") && !name.startsWith("-ms-") && !name.startsWith("-moz-"))
  .filter((name) => properties[name].status !== "obsolete")
  .sort()

const lines = []
let line = ""
for (const name of names) {
  if (line !== "" && line.length + name.length + 1 > 110) {
    lines.push(line)
    line = ""
  }
  line += line === "" ? name : ` ${name}`
}
lines.push(line)

const source = `/**
 * The CSS properties a browser knows, in kebab case: what \`element.style\` stores when Ghia has no
 * style key for one (\`touch-action\`, \`user-select\`) and ignores for a name that is no property at all.
 *
 * Generated by \`scripts/generate-css-property-names.mjs\` from \`mdn-data\` ${version}; do not edit.
 */
export const CSS_PROPERTY_NAMES: ReadonlySet<string> = new Set(
  [
${lines.map((text) => `    "${text}",`).join("\n")}
  ]
    .join(" ")
    .split(" ")
)
`
writeFileSync(new URL("../js/dom/css-property-names.ts", import.meta.url), source)
console.log(`${names.length} properties`)
